#!/usr/bin/env python3
"""Render the project manual from ``docs/*.md`` into the public site.

WHY A GENERATOR AND NOT HAND-WRITTEN PAGES
------------------------------------------
The manual already exists as Markdown in ``docs/`` and is what the team edits.
Re-typing it as HTML creates a second copy, and the second copy is the one that
goes stale in public. So the site pages are DERIVED, committed to git, and
``tests/test_docs_publication.py`` fails the suite if they no longer match the
Markdown. The site itself stays a plain static tree with no build step at serve
time — the reason ``site/README.md`` gives for having no Jekyll.

WHY REDACTION IS NOT OPTIONAL
-----------------------------
``site/`` is published to GitHub Pages by the production sync. Eleven of the
Markdown files carry real internal identifiers: RFC1918 addresses, ``.mx``
management hostnames, hypervisor names, node names, the backup server and an
administrator's e-mail. Publishing them verbatim is an inventory disclosure —
the exact class of leak the release pipeline's secret scan exists to stop.

Two passes, in this order:

1. ``redact()`` rewrites known internal identifiers to angle-bracket
   placeholders, so the published text still reads as documentation.
2. ``scan()`` re-checks the OUTPUT and **aborts the whole run** on any hit,
   naming pattern, file and line. It never warns and continues: a warning in a
   publication pipeline is a leak with a paper trail.

Device SHORT names (``fadc``, ``faz``, ``fortiweb``) are deliberately NOT
redacted — they are ADOM keys and URL segments of the product itself
(``/fadc/api/``), and rewriting them would mangle route documentation while
disclosing nothing: a label with no address is not an inventory.
"""
