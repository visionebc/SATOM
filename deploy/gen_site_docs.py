def source_for(md_name: str) -> pathlib.Path:
    """Where a published document actually lives.

    Most sit in ``docs/``. The changelog sits at the repo root because that
    is where every other tool looks for it (Keep a Changelog, the forge, the
    release pipeline); copying it into ``docs/`` would create a second copy
    that rots. One resolver so the presence check and the renderer cannot
    disagree about which files exist.
    """
    in_docs = DOCS_DIR / md_name
    return in_docs if in_docs.is_file() else ROOT_DIR / md_name


def render_doc(md_name: str, slug: str, title: str, icon: str, blurb: str) -> str:
    import markdown as md_lib

    source = source_for(md_name)
    raw = source.read_text(encoding="utf-8")
    # Redact BEFORE rendering: the placeholder then flows into code blocks and
    # link text alike, and there is no HTML-escaping seam to get wrong.
    raw = redact(raw)

    # No nl2br here, unlike the in-app renderer: these files are hard-wrapped at
    # ~90 columns, and nl2br would turn every wrap into a visible line break.
    md = md_lib.Markdown(extensions=["toc", "fenced_code", "tables", "sane_lists", "attr_list"],
                         output_format="html5")
    body = md.convert(raw)

    # toc_tokens is a TREE, not a list: the only top-level token is the H1, so
    # filtering it directly produced a one-entry table of contents. Flatten,
    # then keep h2 — the H1 is hidden in the page body anyway (the page header
    # already carries the title).
    def _flat(tokens):
        for t in tokens:
            yield t
            yield from _flat(t.get("children") or [])

    toc = [t for t in _flat(getattr(md, "toc_tokens", []))
           if t.get("name") and t.get("level") == 2]
    if not toc:  # a document written entirely with h1/h3 still gets a usable TOC
        toc = [t for t in _flat(getattr(md, "toc_tokens", []))
               if t.get("name") and t.get("level") in (1, 3)]
    toc_html = "\n".join(
        '      <a href="#{}">{}</a>'.format(html.escape(t["id"]), html.escape(t["name"]))
        for t in toc[:45])

    parts = [head(title, blurb, "../", "docs.html")]
    parts.append(f"""
<header class="page wrap">
  <p class="eyebrow"><a href="../docs.html" style="color:inherit;text-decoration:none;">← Documentation</a></p>
  <h1>{icon} {html.escape(title)}</h1>
  <p class="sub">{html.escape(blurb)}</p>
  <div class="callout" style="margin-top:18px;">
    <span class="cico">🕶️</span>
    <p><b>Published copy.</b> Internal addresses, hostnames and device names are replaced
    with <code>{{placeholders}}</code>. The unredacted original is <code>{html.escape(source.relative_to(ROOT_DIR).as_posix())}</code>
    in the repository and is rendered inside the application at <code>/docs</code>.</p>
  </div>
</header>

<section class="wrap reveal">
  <div class="doc">
    <aside class="toc">
      <div class="toc-title">On this page</div>
{toc_html}
    </aside>
    <div class="doc-body mdx">
{body}
    </div>
  </div>
</section>
""")
    parts.append(foot("../"))
    return "".join(parts)


def render_hub() -> str:
    by_slug = {slug: (icon, title, blurb) for _md, slug, title, icon, blurb in PAGES}
    parts = [head("Documentation",
                  "The complete SATOM manual: overview, user guide, installation, operator "
                  "console, privilege model, safeguards, API and device reference.",
                  "", "docs.html")]
    parts.append("""
<header class="page wrap">
  <h1>The <span class="grad">manual</span></h1>
  <p class="sub">Every document that ships with SATOM, in reading order. The same
  Markdown is rendered inside the application at <code>/docs</code> for signed-in
  users; the recovery procedures are also readable from the console itself with
  <code>satom show runbook</code>, on a node with no browser and no internet.</p>
</header>
""")
    for name, lead, slugs in GROUPS:
        cards = []
        for slug in slugs:
            icon, title, blurb = by_slug[slug]
            cards.append(
                f'    <div class="card"><div class="ico">{icon}</div>'
                f'<h3><a href="docs/{slug}.html">{html.escape(title)}</a></h3>'
                f'<p>{html.escape(blurb)}</p></div>')
        parts.append(f"""
<section class="wrap reveal">
  <div class="sec-head">
    <span class="eyebrow">{html.escape(name)}</span>
    <h2>{html.escape(lead)}</h2>
  </div>
  <div class="grid">
{chr(10).join(cards)}
  </div>
</section>
""")
    parts.append(foot(""))
    return "".join(parts)


def build() -> dict[pathlib.Path, str]:
    out: dict[pathlib.Path, str] = {}
    for md_name, slug, title, icon, blurb in PAGES:
        out[OUT_DIR / f"{slug}.html"] = render_doc(md_name, slug, title, icon, blurb)
    out[HUB] = render_hub()
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the published pages are stale; write nothing")
    args = ap.parse_args()

    missing = [m for m, *_ in PAGES if not source_for(m).is_file()]
    if missing:
        print("error: missing source documents: " + ", ".join(missing), file=sys.stderr)
        return 2

    pages = build()

    findings: list[str] = []
    for path, text in pages.items():
        findings.extend(scan(text, path.relative_to(ROOT_DIR).as_posix()))
    if findings:
        print("ABORTED — internal identifiers survived redaction:", file=sys.stderr)
        for f in findings[:40]:
            print("  " + f, file=sys.stderr)
        if len(findings) > 40:
            print(f"  … and {len(findings) - 40} more", file=sys.stderr)
        return 1

    stale = [p for p, t in pages.items()
             if not p.is_file() or p.read_text(encoding="utf-8") != t]
    if args.check:
        if stale:
            print("published documentation is STALE:", file=sys.stderr)
            for p in stale:
                print("  " + p.relative_to(ROOT_DIR).as_posix(), file=sys.stderr)
            print("run: python3 deploy/gen_site_docs.py", file=sys.stderr)
            return 1
        print(f"published documentation is current ({len(pages)} pages)")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in pages.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(pages)} pages ({len(stale)} changed), 0 leaks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
