#!/usr/bin/env bash
# Finish an update that an OLDER update runner applied.
#
# [SATOM-UPGRADE-CONVERGE]
#
# WHY THIS EXISTS. An update is applied by the runner that is INSTALLED on the
# node, not by the one in the release being applied. A 2.x runner jumping a node
# to 3.x therefore does only what 2.x knew about:
#   * it copies the unit list it computed at import time (its own release), so a
#     unit introduced later -- satom-scripts.{path,service}, 3.2.0 -- is never
#     installed and the Script Library queue never drains;
#   * it never runs install-console-role.sh (3.2.0), so the SQL console refuses
#     every query for want of its read-only role;
#   * nothing seeds the scheduled actions 3.x added (knowledge_fetch,
#     signature_check, observatory_scan, hsts_preload_refresh).
# The update still ends green. The next update, applied by the new runner, would
# fix the first two -- until then the node is half-done and says nothing.
#
# The one root-side file every runner since 2.x executes from the NEW tree is
# deploy/install-runner.sh, so that script calls this one when its parent is the
# update runner. Running it under a current runner is harmless: every step only
# fills what is missing.
#
# Idempotent. Run as root. NEVER fails an update: every problem is a WARN line
# and the exit status is always 0. install-runner.sh caps it at 150 s, inside the
# 180 s an old runner gives that script.
#
# By hand: sudo bash /opt/satom/deploy/upgrade-converge.sh
set -uo pipefail

APP_DIR="${FM_APP_DIR:-/opt/satom}"
DEPLOY_SRC="${SATOM_DEPLOY_SRC:-${APP_DIR}/deploy}"
SYSTEMD_DIR="/etc/systemd/system"
STATE_DIR="/var/lib/satom-runner"
# Shared with self_update_runner.py: units armed once and never re-armed, so an
# operator who disables one afterwards keeps it disabled.
ARMED_REGISTRY="${STATE_DIR}/armed-units.json"
SEED_MARKER="${STATE_DIR}/upgrade-seeded-3x"
# A SYSTEM interpreter, never the venv: the venv is the service account's, and
# this script runs as root (also when an operator runs it by hand).
PY="${SATOM_RUN_PY:-/usr/bin/python3}"
case "$PY" in "${APP_DIR}"/*) PY=/usr/bin/python3 ;; esac
# Same as self_update_runner._LATE_ARM: installed by an earlier update but never
# enabled, because the runner of that time enabled nothing.
LATE_ARM="satom-scripts.path"

if [ "$(id -u)" -ne 0 ]; then
  echo "upgrade-converge.sh: must run as root." >&2
  exit 0
fi
cd /tmp 2>/dev/null || cd /

warn() { echo "WARN converge: $*"; }

APP_USER="$(stat -c %U "$APP_DIR" 2>/dev/null || echo root)"

registry_has() {
  [ -x "$PY" ] && [ -f "$ARMED_REGISTRY" ] || return 1
  "$PY" -c 'import json,sys
try: d=json.load(open(sys.argv[1]))
except Exception: sys.exit(1)
sys.exit(0 if isinstance(d,list) and sys.argv[2] in d else 1)' "$ARMED_REGISTRY" "$1"
}

registry_add() {
  [ -x "$PY" ] || return 0
  mkdir -p "$STATE_DIR" && chmod 0700 "$STATE_DIR"
  "$PY" -c 'import json,sys
p=sys.argv[1]
try: d=json.load(open(p))
except Exception: d=[]
if not isinstance(d,list): d=[]
open(p,"w").write(json.dumps(sorted(set(d)|set(sys.argv[2:]))))' "$ARMED_REGISTRY" "$@" \
    || warn "could not record armed units in ${ARMED_REGISTRY}"
}

# ---- 1. units the applying runner did not know about ---------------------
installed=()
fresh=()
for src in "$DEPLOY_SRC"/*.service "$DEPLOY_SRC"/*.timer "$DEPLOY_SRC"/*.path; do
  [ -f "$src" ] || continue
  unit="$(basename "$src")"
  dst="${SYSTEMD_DIR}/${unit}"
  [ -e "$dst" ] && continue
  if ! install -o root -g root -m 0644 "$src" "$dst"; then
    warn "could not install ${unit}"; continue
  fi
  installed+=("$unit")
  # The templates declare User=root; the drop-in pins the service account
  # (same text as self_update_runner.UNIT_DROPIN). The runner itself stays root.
  if [ "${unit%.service}" != "$unit" ] && [ "$unit" != "satom-updater.service" ] \
     && [ "$APP_USER" != root ]; then
    mkdir -p "${dst}.d"
    cat > "${dst}.d/10-app-user.conf" <<EOF
# Generated by SATOM (installer / migrate-deprivilege.sh / self_update_runner).
# Lives in a drop-in rather than in the unit because the deploy/ templates
# declare User=root and every update re-copies them: the drop-in survives that.
# Do NOT edit by hand.
[Service]
User=${APP_USER}
Group=${APP_USER}
EOF
  fi
  case "$unit" in *.path|*.timer) fresh+=("$unit") ;; esac
done

# The Script Library's queue tree, as the installer creates it: a .path unit
# watching a directory that does not exist never fires.
if [ -f "${DEPLOY_SRC}/satom-scripts.path" ] && [ "$APP_USER" != root ]; then
  install -d -o "$APP_USER" -g "$APP_USER" -m 0750 \
      "$APP_DIR/data/scripts" "$APP_DIR/data/scripts/library" \
      "$APP_DIR/data/scripts/queue" "$APP_DIR/data/scripts/claimed" \
      "$APP_DIR/data/scripts/status" 2>/dev/null || warn "could not create ${APP_DIR}/data/scripts"
fi

systemctl daemon-reload 2>/dev/null || true

late=()
for unit in $LATE_ARM; do
  [ -e "${SYSTEMD_DIR}/${unit}" ] || continue
  case " ${fresh[*]-} " in *" ${unit} "*) continue ;; esac
  registry_has "$unit" && continue
  systemctl is-enabled --quiet "$unit" 2>/dev/null && continue
  late+=("$unit")
done

armed=()
for unit in "${fresh[@]+"${fresh[@]}"}" "${late[@]+"${late[@]}"}"; do
  if timeout 15 systemctl enable --now "$unit" >/dev/null 2>&1; then
    armed+=("$unit")
  else
    warn "could not enable ${unit}"
  fi
done
[ "${#armed[@]}" -gt 0 ] && registry_add "${armed[@]}"

if [ "${#installed[@]}" -gt 0 ] || [ "${#armed[@]}" -gt 0 ]; then
  echo "converge: units installed: ${installed[*]:-none}; armed: ${armed[*]:-none}"
else
  echo "converge: units already complete"
fi

# The Script Library refuses to run without its jail. Installing an OS package
# is an operator act (Settings > General > System packages), so only say so.
if [ -f "${DEPLOY_SRC}/satom-scripts.path" ] && ! command -v bwrap >/dev/null 2>&1; then
  warn "bubblewrap (bwrap) is not installed: the Script Library will refuse runs until it is (Settings > General > System packages)"
fi

# ---- 2. the SQL console's read-only role (primary only) ------------------
if [ -f "${DEPLOY_SRC}/install-console-role.sh" ]; then
  out="$(FM_APP_DIR="$APP_DIR" timeout 30 bash "${DEPLOY_SRC}/install-console-role.sh" 2>&1)" \
    && echo "converge: $(printf '%s' "$out" | tail -n 1)" \
    || warn "console role: $(printf '%s' "$out" | tail -n 1)"
fi

# ---- 3. scheduled actions introduced by 3.x (primary only, once) ---------
# --upgrade creates only rows outside the 2.11.0 plan, so it cannot bring back an
# action the operator deleted; the marker keeps it to a single pass.
CLI="$(command -v satom || true)"
[ -n "$CLI" ] || { [ -x /usr/local/sbin/satom ] && CLI=/usr/local/sbin/satom; }
if [ -e "$SEED_MARKER" ]; then
  echo "converge: 3.x scheduled actions already seeded"
elif [ -z "$CLI" ]; then
  warn "satom CLI not found; run 'sudo satom execute seed actions --yes' on the primary"
else
  out="$(timeout 100 "$CLI" execute seed actions --yes --upgrade 2>&1)"; rc=$?
  first="$(printf '%s' "$out" | grep -m1 -E 'created|already armed|refusing' || true)"
  if [ "$rc" -eq 0 ]; then
    mkdir -p "$STATE_DIR" && chmod 0700 "$STATE_DIR" && : > "$SEED_MARKER"
    echo "converge: scheduled actions: ${first:-done}"
  elif printf '%s' "$out" | grep -q 'standby'; then
    echo "converge: scheduled actions: standby, they arrive by replication"
  else
    warn "seeding scheduled actions failed (rc ${rc}); run 'sudo satom execute seed actions --yes' on the primary"
  fi
fi

exit 0
