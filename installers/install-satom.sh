# ---- pg_hba: the app's local TCP connection -------------------------------
# The distro default CANNOT be trusted: Debian ships scram-sha-256 for
# 127.0.0.1 but openSUSE/SLES ships *ident*, which rejects the app user with
# FATAL before looking at the password. The rule is INSERTED AT THE TOP
# because pg_hba is first-match: appended at the end it would sit behind the
# distro's generic rule and never be evaluated.
if ! grep -q "SATOM-LOCAL" "$PGHBA"; then
    TMPHBA=$(mktemp)
    {
        echo "# SATOM-LOCAL (install-satom.sh) — first-match: goes on top"
        echo "host    ${DB_NAME}   ${DB_USER}   127.0.0.1/32   scram-sha-256"
        echo "host    ${DB_NAME}   ${DB_USER}   ::1/128        scram-sha-256"
        cat "$PGHBA"
    } > "$TMPHBA"
    cat "$TMPHBA" > "$PGHBA"
    rm -f "$TMPHBA"
    ok "pg_hba: local scram rule for ${DB_USER}@${DB_NAME}"
fi

# ---- RELOAD: writing pg_hba is not enough ---------------------------------
# [SATOM-HBA-RELOAD] Postgres evaluates pg_hba from MEMORY. Without a reload,
# the rule just written does not exist for the running server.
# The only `systemctl restart postgresql` lived inside the `primary` branch,
# so a STANDALONE install wrote the right rule and the server kept applying
# the distro's generic one. On Debian that goes unnoticed (its default for
# 127.0.0.1 is already scram-sha-256); on openSUSE and RHEL the default is
# *ident* -> `flask create-db` died with
#   FATAL: Ident authentication failed for user "satom"
# It goes here, outside any branch, for ALL modes.
systemctl reload postgresql >>"$INSTALL_LOG" 2>&1 \
    || systemctl restart postgresql >>"$INSTALL_LOG" 2>&1 \
    || die "Could not reload PostgreSQL after writing pg_hba (check $INSTALL_LOG)"

# [SATOM-HBA-VERIFY] Check the credential HERE, not 100 lines further down
# inside an SQLAlchemy traceback. This is the point where the error is
# actionable and the message can name the cause.
if [ "$ROLE" != "secondary" ]; then
    if PGPASSWORD="$DB_PASS" psql -h 127.0.0.1 -U "$DB_USER" -d "$DB_NAME" \
            -tAc 'SELECT 1' >>"$INSTALL_LOG" 2>&1; then
        ok "PostgreSQL reloaded — the app can authenticate over TCP"
    else
        die "Account '${DB_USER}' cannot connect to 127.0.0.1/${DB_NAME}.
       Usual cause: pg_hba not reloaded, or an earlier, more generic rule
       (e.g. 'host all all 127.0.0.1/32 ident') wins the first match.
       Check: ${PGHBA} and ${INSTALL_LOG}"
    fi
else
    ok "PostgreSQL reloaded — pg_hba in effect"
fi

