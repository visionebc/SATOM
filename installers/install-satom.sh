# [SATOM-NGINX-DEFAULT] The TLS listener has to claim default_server.
# Without an explicit owner, nginx grants it to the FIRST server on
# :${WEB_PORT} in parse order, which across files is ALPHABETICAL. As soon as
# a second vhost lives alongside — e.g. the static site the manual documents —
# the console stops answering by hostname while the other site keeps serving,
# and that reads as a DNS failure, not an nginx one. Production nodes carry
# `default_server` because someone got bitten and added it by hand; the
# installer kept emitting the version from BEFORE that fix, so every new
# install was born with the latent fault and `satom diagnose nginx` flagged
# it FAIL on day zero.
# An explicit :443 in a redirect is valid but leaks into the address bar and
# into any proxy in front; it is omitted when it is the default port, just
# like the browser does.
REDIR_PORT=""
if [ "$WEB_PORT" != "443" ]; then REDIR_PORT=":${WEB_PORT}"; fi
write_satom_vhost() {
    local dflt="$1"
cat > "$NGXCONF" <<NGX
server {
    listen ${WEB_PORT} ssl http2${dflt};
    server_name ${SERVED_NAMES} ${NODE_IP};
    ssl_certificate     ${PKI}/public/server.crt;
    ssl_certificate_key ${PKI}/public/server.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    # Must be >= MAX_UPLOAD_BYTES in update_package_service.py, or a
    # valid update package dies with an nginx 413 that the app never
    # sees and therefore cannot explain.
    client_max_body_size 400M;
    location / {
        proxy_pass http://127.0.0.1:8000;
        # [SATOM-VHOST-HOST] \$host DROPS the port; \$http_host passes the
        # header through as is. Flask-WTF builds the expected CSRF origin from
        # the host the app thinks it has and compares it with the browser's
        # Referer INCLUDING the port: behind NAT or a proxy on a non-standard
        # port, EVERY POST -- login included -- died with an error that talked
        # about an expired session rather than the header. On :443 they are
        # identical, because the browser omits the default port.
        proxy_set_header Host \$http_host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_read_timeout 120s;
    }
}
# ACME http-01 (webroot) — the Certificate Manager's "web authentication" mode.
# The CA ALWAYS validates over plain :80, so this listener exists even though the
# app is served over TLS. The redirect is scoped to "location /" on purpose: a
# server-level "return" runs before location selection and would swallow the
# challenge. Not needed if you validate with dns-01.
server {
    listen 80${dflt};
    listen [::]:80${dflt};
    server_name _;
    location ^~ /.well-known/acme-challenge/ {
        root ${ACME_WEBROOT};
        default_type "text/plain";
        try_files \$uri =404;
    }
    location / { return 301 https://\$host${REDIR_PORT}\$request_uri; }
}
