# ---- [SATOM-OVERLAY-SEED] site publication rules --------------------------
# app/services/doc_publication._load_overlay FAILS CLOSED on purpose: on a
# deployed node (.env exists) without data/publication-rules.local.json the app
# does not import, because redacting with only the generic rules would be a
# fail-open. Neither the public repo nor the bundles carry that file (it is
# site-specific and in .gitignore), so in 2.1.1 `flask create-db` died on
# EVERY new install. A new install has no rules of its own: its correct
# content is '{}'. It is created ONLY if it does not exist -- neither in data/
# nor at the legacy root path, which the loader also reads: seeding data/ on
# top of a root with real rules would silently hide them. It is never
# overwritten. On a secondary the first datasync replaces it with the
# primary's copy.
# Runs BEFORE writing .env and before any app import (sealing, create-db).
ensure_publication_overlay() {
    local f="$APP_DIR/data/publication-rules.local.json"
    if [ -e "$f" ] || [ -e "$APP_DIR/publication-rules.local.json" ]; then
        ok "Site publication rules present — left untouched"
        return 0
    fi
    mkdir -p "$APP_DIR/data"
    ( umask 022; printf '{}\n' > "$f" )
    chown "${APP_USER}:${APP_USER}" "$f"
    chmod 644 "$f"
    ok "Site publication rules: created empty ${f} ({})"
}
