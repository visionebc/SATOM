        ok "Primary reachable (healthz 200)"
    else
        warn "Could not verify https://${PRIMARY_IP}:${PRIMARY_PORT:-443}/healthz — continuing, but replication will fail if the primary is not reachable"
    fi
else
    # 1d. Administrator password (standalone/primary only; the secondary inherits it via replication)
    ADMIN_PASS=""
    while [ -z "$ADMIN_PASS" ]; do
