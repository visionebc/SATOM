# systemd units
# Pins the service account via a DROP-IN, not by editing the unit: the deploy/
# templates declare User=root and the self-update runner copies them again on
# every update — without the drop-in, the first update would put the app back
# on root.
satom_enforce_unit_user() {                                          # [PFDROPIN]
    local unit d
    for unit in satom.service satom-scheduler.service satom-reconciler.service \
                satom-alerts.service satom-cert-renew.service \
                satom-metrics.service satom-ha-datasync.service; do
        [ -f "/etc/systemd/system/$unit" ] || continue
        d="/etc/systemd/system/${unit}.d"
        install -d -m 0755 "$d"
        cat > "$d/10-app-user.conf" <<DROPIN
# Generated by install-satom.sh. Lives in a drop-in because the deploy/
# templates declare User=root and every update copies them again. Do NOT edit by hand.
[Service]
User=${APP_USER}
Group=${APP_USER}
DROPIN
    done
    systemctl daemon-reload
    ok "Service account pinned via drop-in (survives updates)"
}

