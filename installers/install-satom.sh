# --- SATOM-SSHD-ENABLE -----------------------------------------------------
# Installing openssh is NOT the same as having sshd running. On Debian the
# .deb enables it by policy and the datasync channel works by luck; on
# openSUSE the service stays disabled/inactive and nothing listens on :22, so
# the standby can never pull data/. It is enabled on BOTH cluster nodes:
# after a promote it is the old standby that has to serve the pull.
if [ "$MODE" = "cluster" ]; then
    SSHD_UNIT=""
    for u in sshd.service ssh.service; do
        systemctl list-unit-files "$u" >/dev/null 2>&1 \
            && systemctl cat "$u" >/dev/null 2>&1 && { SSHD_UNIT="$u"; break; }
    done
    if [ -z "$SSHD_UNIT" ]; then
        warn "No sshd/ssh unit found — the data/ datasync will NOT work until an SSH server is active"
    else
        systemctl enable --now "$SSHD_UNIT" >>"$INSTALL_LOG" 2>&1 || true
        if systemctl is-active --quiet "$SSHD_UNIT"; then
            ok "SSH server active (${SSHD_UNIT}) — data/ replication channel available"
