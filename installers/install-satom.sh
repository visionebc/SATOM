# ─────────────────────────────────────────────────────────────────────────────
# [SATOM-SEAL-PASSPHRASE] Off-node custody, sealed.
#
# NO automatic copy carries FERNET_KEY or the internal CA key: not git (they
# are outside the tree / in .gitignore), not the datasync (it only carries
# data/) and not the bundle (on purpose: a bundle is retained, replicated to
# the peer and pushed over SFTP with a password that lives in a column that
# FERNET_KEY opens — in the clear there, a single stolen file is the whole
# estate).
#
# The SEALED envelope inverts that asymmetry: it travels in data/, so the
# datasync AND the bundle carry it, and whoever steals a copy gets ciphertext.
# The operator, with only a passphrase, rebuilds the install from ANY copy.
#
# It is created at INSTALL time, not only when joining the cluster: a
# standalone node never joins and is precisely the one with no other copy.
# The secondary INHERITS it through the join key so both nodes open the same
# envelope. That adds no new class of secret to the join key — it already
