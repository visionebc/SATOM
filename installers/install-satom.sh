    # The legacy OFMJOIN1. prefix is accepted so keys already issued stay
    # valid; new ones are always issued as SATOMJOIN1.
    case "$JOIN_KEY_RAW" in
        SATOMJOIN1.*) JOIN_B64="${JOIN_KEY_RAW#SATOMJOIN1.}" ;;
        OFMJOIN1.*)   JOIN_B64="${JOIN_KEY_RAW#OFMJOIN1.}" ;;
        *) die "Invalid join key (it must start with SATOMJOIN1.)" ;;
    esac
    JOIN_JSON=$(echo "$JOIN_B64" | base64 -d 2>/dev/null) || die "The join key could not be decoded"
    # JSON extractor in shell. Python CANNOT be used here: this is step 1 and
    # the interpreter is installed in step 2 — on a distro without a python3
    # symlink this died with exit 127 right after pasting the key. The key is
    # generated by this very installer (json.dump of a flat dict of strings:
    # one line, no nesting, \n escaped inside the PEMs).
    # It is ALWAYS used, not as a fallback branch: a second path that only
    # runs on one distro family is untested code.
    _SATOM_JSON_AWK=$(cat <<'AWKJSON'
{ all = all $0 }
END {
    pat = "\"" k "\"[ ]*:[ ]*\""
    if (match(all, pat) == 0) exit 1
    i = RSTART + RLENGTH
    out = ""
    n = length(all)
    while (i <= n) {
        c = substr(all, i, 1)
        if (c == "\\") {
            e = substr(all, i + 1, 1)
            if (e == "n")      out = out "\n"
            else if (e == "t") out = out "\t"
            else if (e == "r") out = out "\r"
            else               out = out e
            i += 2
        } else if (c == "\"") {
            break
        } else {
            out = out c
            i++
        }
    }
    printf "%s", out
}
AWKJSON
)
    json_str_field() { awk -v k="$1" "$_SATOM_JSON_AWK"; }
