# 1b2. Served DNS names                                       [SATOM-SERVED-NAMES]
# The names this node is REACHED by must be known HERE, because TWO things are
# minted from them that cannot be fixed later without reissuing: the vhost's
# server_name and the SAN list of the node certificate.
# Plain `hostname` is the SHORT name. A node reached at console.example.tld was
# born with `server_name console` -- which only answered because the vhost also
# claimed default_server, i.e. by accident -- and with a certificate whose SAN
# said DNS:console, so EVERY browser coming in through the FQDN got a name
# mismatch warning on a certificate the installer had just reported as good.
# The data was available (`hostname -f`) and was not used.
DEFAULT_NAMES="$(hostname -f 2>/dev/null || true)"
if [ -z "$DEFAULT_NAMES" ]; then DEFAULT_NAMES="$(hostname)"; fi
if [ -n "${SATOM_SERVED_NAMES:-}" ]; then
    SERVED_NAMES="$SATOM_SERVED_NAMES"
else
