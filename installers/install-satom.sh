#!/usr/bin/env bash
# ============================================================================
# install-satom.sh — SATOM (System Automation & Task Orchestration Manager)
# installer — GENERIC for Linux distributions running systemd.
#
#   Supported families (package manager detected automatically):
#     • Debian / Ubuntu ............. apt
#     • RHEL / Rocky / Alma / Fedora  dnf (or yum)
#     • openSUSE / SLES ............. zypper
#     • Arch ........................ pacman
#   Hard requirement: systemd (the app installs systemd units). Alpine/musl
#   is not supported.
#
# OPERATING MODES
#   • ONLINE : downloads packages from the distro/PyPI mirrors and the code
#              from the production git repo. Works on ALL families.
#   • OFFLINE: 100% without network. Enabled automatically when a `bundle/`
#              directory sits next to this script (generated by
#              build-offline-bundle*.sh) with the packages, wheels/ and
#              app.tar.gz. Each bundle carries the packages of ONE family
#              (debs/, rpms/ or rpms-suse/); for any other family use
#              online mode.
#
# TOPOLOGIES
#   • standalone            — a single node, local Postgres.
#   • cluster / primary     — generates the JOIN KEY that is pasted into the
#                             secondary node.
#   • cluster / secondary   — asks for the join key; sets up Postgres streaming
#                             replication + data/ datasync and ISSUES ITS OWN
#                             CERTIFICATE signed by the cluster's internal CA.
#
# EXECUTION ORDER (consistent: EVERYTHING is asked first, then installed)
#   1. Questions: IP, HTTPS port, admin password, standalone/cluster,
#      primary/secondary (+join key if secondary).
#   2. Package check (installs what is missing / warns about outdated ones).
#   3. Application code + Python virtual environment.
#   4. Postgres (local DB, or replica if secondary).
#   5. PKI and TLS certificates.
#   6. systemd services + nginx.
#   7. Health check and summary (join key on the primary).
#
# REQUIRES: root (or sudo). See docs/INSTALL.md for the exact command list
# if the systems team prefers a granular sudoers rule.
# ============================================================================
set -euo pipefail

VERSION="2.1.2"
APP_DIR="/opt/satom"
ACME_WEBROOT="/var/www/acme"
LEGO_VERSION="5.2.2"
VM_VERSION="1.148.0"
VM_SHA256="bde7ea38c7c9b341a0bb1f37294d6d619ff0318d70174008b57d83cd4f5698f3"   # victoria-metrics-prod, release checksums
LOG_DIR="/var/log/satom"
# Unprivileged service account. The app does NOT run as root: see
# docs/privilege-model.md. Can be overridden to migrate a legacy install
# that already uses another name (e.g. SATOM_APP_USER=fortinet).
APP_USER="${SATOM_APP_USER:-satom}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUNDLE_DIR="${SCRIPT_DIR}/bundle"
# Public source of record. The previous default pointed at a private Gitea
# that only resolves inside one company's network, so an unattended install
# anywhere else hung on a clone it could never complete.
GIT_URL_DEFAULT="https://github.com/visionebc/SATOM.git"
DB_NAME="satom"
DB_USER="satom"
REPL_USER="fm_repl"
INSTALL_LOG="/var/log/satom-install.log"

c_bold=$'\033[1m'; c_grn=$'\033[32m'; c_ylw=$'\033[33m'; c_red=$'\033[31m'; c_off=$'\033[0m'
say()  { echo "${c_bold}==>${c_off} $*" | tee -a "$INSTALL_LOG"; }
ok()   { echo "    ${c_grn}✓${c_off} $*" | tee -a "$INSTALL_LOG"; }
warn() { echo "    ${c_ylw}!${c_off} $*" | tee -a "$INSTALL_LOG"; }
die()  { echo "${c_red}ERROR:${c_off} $*" | tee -a "$INSTALL_LOG" >&2; exit 1; }

# ── Prompt input ───────────────────────────────────────── [SATOM-LOUD-READ]
# `read` returns !=0 on EOF. Under `set -euo pipefail` that kills the
# installer WITHOUT PRINTING ANYTHING: the last line the operator sees is the
# previous step's and rc=1 does not say where it died. It happens whenever the
# installer is driven through a pipe or here-doc and the answer sequence is
# shorter than the prompt sequence — and the ONLINE and OFFLINE paths do NOT
# ask the same number of questions (online also asks for the repo URL). Same
# class of failure as [SATOM-LOUD-DB]: a silent failure is one nobody finds.
# EVERY installer prompt goes through here.
#   EOF with partial data (last line without a newline) IS a valid answer and
#   is accepted — just like Ctrl-D after typing in a terminal.
_ask_die() {
    die "No answer for the prompt: \"$1\"
    Input ran out (EOF). If you drive the installer through a pipe or here-doc,
    the answer sequence is shorter than the prompt sequence: the ONLINE path
    asks for the repo URL and the OFFLINE path does not. Run it interactively,
    or add the missing answer."
}
ask() {                                  # ask VAR "prompt"  -> reads into $VAR
    local __v="$1" __p="$2" __rc=0
    read -rp "$__p" "$__v" || __rc=$?
    [ "$__rc" -eq 0 ] || [ -n "${!__v:-}" ] || _ask_die "$__p"
}
ask_secret() {                           # ask_secret VAR "prompt"  -> no echo
    local __v="$1" __p="$2" __rc=0
    read -rsp "$__p" "$__v" || __rc=$?
    echo
    [ "$__rc" -eq 0 ] || [ -n "${!__v:-}" ] || _ask_die "$__p"
}

# ─────────────────────────────────────────────────────────────────────────────
# SUBCOMMAND: --print-sudoers  (does NOT need root — runs before the check)
# Prints the sudoers rule for the INSTALLER ACCOUNT, so it can be handed to the
# systems team without sending them the whole repository. Installing SATOM is
# root work; what this rule avoids is HANDING OVER THE ROOT PASSWORD: a named
# account is given that can only launch one binary at a fixed path. Not to be
# confused with /etc/sudoers.d/satom, the RUNTIME's two-command allowlist.
#   sudo bash install-satom.sh --print-sudoers > /etc/sudoers.d/satom-installer
#   visudo -c
# ─────────────────────────────────────────────────────────────────────────────
if [ "${1:-}" = "--print-sudoers" ]; then
    INSTALLER_USER="${2:-satominstall}"
    cat <<SUDOEOF
# /etc/sudoers.d/satom-installer — permission to RUN THE INSTALLER.
# Generated by: install-satom.sh --print-sudoers ${INSTALLER_USER}
#
# Requirements for this to be safe:
#   install -d -m 0755 /opt/staging
#   install -m 0755 install-satom.sh /opt/staging/install-satom.sh
#   chown root:root /opt/staging/install-satom.sh   # the operator must NOT be able to edit it
# If the operator could write that file, the rule amounts to NOPASSWD: ALL.
#
# Remove when the installation window closes:
#   rm /etc/sudoers.d/satom-installer

Cmnd_Alias SATOM_INSTALL = /usr/bin/bash /opt/staging/install-satom.sh, \\
                           /usr/bin/bash /opt/staging/install-satom.sh --preflight, \\
                           /usr/bin/bash /opt/staging/install-satom.sh --check, \\
                           /usr/bin/bash /opt/staging/install-satom.sh --authorize-peer *

${INSTALLER_USER} ALL=(root) NOPASSWD: SATOM_INSTALL
SUDOEOF
    exit 0
fi

[ "$(id -u)" -eq 0 ] || die "Run as root (or with sudo): sudo bash $0"
mkdir -p "$(dirname "$INSTALL_LOG")"; touch "$INSTALL_LOG"

# ─────────────────────────────────────────────────────────────────────────────
# SUBCOMMAND: --authorize-peer <standby-ip> "<ssh-public-key>"
# Runs on the PRIMARY to trust a standby. Replaces the old model where the
# primary generated the key pair and shipped the PRIVATE half inside the join
# key. Only a PUBLIC key comes in here, and a restricted one at that:
#   from=      → only from the standby's IP
#   restrict   → no pty, no agent/port/X11 forwarding, no user-rc
#   command=   → only a READ-ONLY rsync of data/ (our own wrapper)
# ─────────────────────────────────────────────────────────────────────────────
if [ "${1:-}" = "--authorize-peer" ]; then
    PEER_IP="${2:-}"; PEER_PUBKEY="${3:-}"
    [ -n "$PEER_IP" ] && [ -n "$PEER_PUBKEY" ] \
        || die "Usage: $0 --authorize-peer <standby-ip> \"<ssh-public-key>\""
    [[ "$PEER_IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] \
        || die "Invalid standby IP: $PEER_IP"
    [[ "$PEER_PUBKEY" == ssh-ed25519\ * || "$PEER_PUBKEY" == ssh-rsa\ * ]] \
        || die "That does not look like an SSH public key (it must start with ssh-ed25519 or ssh-rsa)"
    id -u "$APP_USER" >/dev/null 2>&1 || die "Service user ${APP_USER} does not exist — was this node installed?"

    # ---- SHELL FOR THE DATASYNC -----------------------------------------
    # The service account is 'nologin' by default, which is correct as long
    # as it receives no SSH. This subcommand is exactly the point where we
    # decide that it DOES: sshd runs the login shell to launch the forced
    # command, so with nologin the connection is always refused.
    # The minimal shell is opened HERE and not earlier. It stays restricted by:
    #   · a locked password (the account has no interactive login)
    #   · from= + restrict + command= in authorized_keys
    CUR_SHELL="$(getent passwd "$APP_USER" | cut -d: -f7)"
    case "$CUR_SHELL" in
        */nologin|*/false)
            SH_BIN="$(command -v sh || echo /bin/sh)"
            usermod -s "$SH_BIN" "$APP_USER"
            warn "Shell for ${APP_USER}: ${CUR_SHELL} → ${SH_BIN} (sshd needs it for the forced command)"
            ;;
    esac
    # The password MUST stay locked: the shell is not a way in.
    passwd -l "$APP_USER" >/dev/null 2>&1 || true

    SHELL_WRAPPER=/usr/local/sbin/satom-ha-rsync-shell
    [ -x "$SHELL_WRAPPER" ] || die "$SHELL_WRAPPER is missing (reinstall or copy deploy/satom-ha-rsync-shell)"

    AK="$APP_DIR/.ssh/authorized_keys"
    install -d -m 700 -o "$APP_USER" -g "$APP_USER" "$APP_DIR/.ssh"
    touch "$AK"; chown "$APP_USER:$APP_USER" "$AK"; chmod 600 "$AK"
    KEYBODY="$(echo "$PEER_PUBKEY" | awk '{print $1" "$2}')"
    if grep -qF "$KEYBODY" "$AK"; then
        ok "That key was already authorized — not duplicated"
    else
        printf 'from="%s",restrict,command="%s" %s\n' \
            "$PEER_IP" "$SHELL_WRAPPER" "$PEER_PUBKEY" >> "$AK"
        ok "Standby ${PEER_IP} authorized (read-only rsync of data/ only)"
    fi
    # ---- SATOM-HANODES-MERGE --------------------------------------------
    # data/ is replicated primary -> standby with `rsync --delete`, so the
    # PRIMARY's ha_nodes.json is the authoritative copy: the two-entry one
    # the installer writes on the secondary is wiped by the first sync.
    # This is the point where the primary learns its peer's IP.
    PEER_NAME="${4:-}"
    if [ -z "$PEER_NAME" ]; then
        PEER_NAME="$(getent hosts "$PEER_IP" 2>/dev/null | awk '{print $2}' | head -1)"
        PEER_NAME="${PEER_NAME%%.*}"
    fi
    [ -n "$PEER_NAME" ] || PEER_NAME="$PEER_IP"
    if [ -x "$APP_DIR/venv/bin/python" ]; then
        SATOM_PEER_IP="$PEER_IP" SATOM_PEER_NAME="$PEER_NAME" \
        SATOM_APP_DIR="$APP_DIR" "$APP_DIR/venv/bin/python" - <<'PYNODES' && \
            chown "$APP_USER:$APP_USER" "$APP_DIR/data/ha_nodes.json" 2>/dev/null || true
import json, os, socket

app = os.environ["SATOM_APP_DIR"]
ip = os.environ["SATOM_PEER_IP"]
name = os.environ["SATOM_PEER_NAME"]
path = os.path.join(app, "data", "ha_nodes.json")

try:
    nodes = json.load(open(path))
    if not isinstance(nodes, list):
        raise ValueError
except Exception:
    nodes = []

# An entry the operator edited in the UI is never overwritten: if the IP is
# already there, it is left as it is.
if not any((n.get("host") or "").strip() == ip for n in nodes):
    if not any((n.get("role") or "") == "primary" for n in nodes):
        nodes.insert(0, {"name": socket.gethostname(), "host": "", "role": "primary"})
    nodes.append({"name": name, "host": ip, "role": "standby"})
    json.dump(nodes, open(path, "w"), indent=2)
    print("  ha_nodes.json: added %s (%s) as standby" % (name, ip))
else:
    print("  ha_nodes.json: %s was already registered" % ip)
PYNODES
    else:
        warn "${APP_DIR}/venv/bin/python not found — register the standby by hand in Software Update → HA nodes"
    fi

    echo ""
    echo "Verify it from the standby:"
    echo "  sudo -u ${APP_USER} ssh -i ${APP_DIR}/.ssh/id_ha_rsync ${APP_USER}@<primary-ip> true"
    echo "  → it must REFUSE the interactive shell. That is correct."
    exit 0
fi

# ─────────────────────────────────────────────────────────────────────────────
# DISTRO ABSTRACTION LAYER — everything family-specific lives here
# ─────────────────────────────────────────────────────────────────────────────
command -v systemctl >/dev/null 2>&1 || die "systemd is required (Alpine/musl is not supported)"

PKG_MGR=""
for m in apt-get dnf yum zypper pacman; do
    command -v "$m" >/dev/null 2>&1 && { PKG_MGR="${m/apt-get/apt}"; break; }
done
[ -n "$PKG_MGR" ] || die "Unsupported package manager. Valid families: apt, dnf/yum, zypper, pacman"

# Package names per family (same order of concepts in all of them)
case "$PKG_MGR" in
    apt)        REQUIRED_PKGS=(python3 python3-venv python3-pip postgresql nginx rsync openssl curl ca-certificates sudo git) ;;
    dnf|yum)    REQUIRED_PKGS=(python3.11 python3.11-pip postgresql-server postgresql nginx rsync openssl curl ca-certificates sudo git) ;;
    zypper)     REQUIRED_PKGS=(python311 python311-pip postgresql-server postgresql nginx rsync openssl curl ca-certificates sudo git) ;;
    pacman)     REQUIRED_PKGS=(python python-pip postgresql nginx rsync openssl curl ca-certificates sudo git) ;;
esac
ONLINE_EXTRA_PKGS=(git)

# SSH packages: installed ONLY in cluster mode (the data/ sync channel is
# rsync over SSH). A standalone node does not need sshd for the product, so
# it is not imposed on it.                                              [PFSSH]
case "$PKG_MGR" in
    apt)        SSH_PKGS=(openssh-client openssh-server) ;;
    dnf|yum)    SSH_PKGS=(openssh-clients openssh-server) ;;
    zypper)     SSH_PKGS=(openssh) ;;
    pacman)     SSH_PKGS=(openssh) ;;
esac

pkg_installed() {  # pkg_installed <pkg> → 0 if installed
    case "$PKG_MGR" in
        apt)     dpkg -s "$1" >/dev/null 2>&1 ;;
        pacman)  pacman -Qi "$1" >/dev/null 2>&1 ;;
        *)       rpm -q "$1" >/dev/null 2>&1 ;;
    esac
}

pkg_version() {  # pkg_version <pkg> → installed version (or "?")
    case "$PKG_MGR" in
        apt)     dpkg-query -W -f='${Version}' "$1" 2>/dev/null || echo "?" ;;
        pacman)  pacman -Qi "$1" 2>/dev/null | awk -F': *' '/^Version/{print $2; exit}' || echo "?" ;;
        *)       rpm -q --qf '%{VERSION}-%{RELEASE}' "$1" 2>/dev/null || echo "?" ;;
    esac
}

pkg_install() {  # pkg_install <pkg...> → installs from the distro mirrors
    case "$PKG_MGR" in
        apt)     export DEBIAN_FRONTEND=noninteractive
                 apt-get update -qq >>"$INSTALL_LOG" 2>&1
                 apt-get install -y -qq "$@" >>"$INSTALL_LOG" 2>&1 ;;
        # --allowerasing: EL9 minimal ships curl-minimal, which conflicts with
        # full curl — dnf must be allowed to swap them.
        dnf)     dnf install -y -q --allowerasing "$@" >>"$INSTALL_LOG" 2>&1 ;;
        yum)     yum install -y -q "$@" >>"$INSTALL_LOG" 2>&1 ;;
        zypper)  zypper --non-interactive --quiet install "$@" >>"$INSTALL_LOG" 2>&1 ;;
        pacman)  pacman -Sy --noconfirm --needed "$@" >>"$INSTALL_LOG" 2>&1 ;;
    esac
}

pg_bootstrap() {  # starts Postgres, initializing the data cluster if needed
    systemctl enable postgresql >>"$INSTALL_LOG" 2>&1 || true
    if systemctl start postgresql >>"$INSTALL_LOG" 2>&1; then return 0; fi
    # RHEL/Fedora ship postgresql-setup; elsewhere run initdb directly in the
    # postgres user's home (Arch: /var/lib/postgres, SUSE: /var/lib/pgsql)
    if command -v postgresql-setup >/dev/null 2>&1; then
        postgresql-setup --initdb >>"$INSTALL_LOG" 2>&1 || true
    else
        local pghome; pghome=$(getent passwd postgres | cut -d: -f6)
        [ -s "$pghome/data/PG_VERSION" ] || \
            runuser -u postgres -- initdb -D "$pghome/data" >>"$INSTALL_LOG" 2>&1 || true
    fi
    systemctl start postgresql >>"$INSTALL_LOG" 2>&1 \
        || die "PostgreSQL did not start after initdb (check $INSTALL_LOG)"
}

OFFLINE=0
if [ -d "$BUNDLE_DIR" ] && [ -d "$BUNDLE_DIR/debs" ]; then
    [ "$PKG_MGR" = "apt" ] || die "The offline bundle contains .deb packages (Debian/Ubuntu family) and this machine uses ${PKG_MGR}. Run the installer in ONLINE mode (delete or rename bundle/) or build the bundle for this family."
    OFFLINE=1
elif [ -d "$BUNDLE_DIR" ] && [ -d "$BUNDLE_DIR/rpms-suse" ]; then
    # A directory of its own on purpose: both bundles are .rpm and they are
    # NOT interchangeable (python311 vs python3.11, different base libraries,
    # and zypper and dnf do not read repos the same way). Keeping them apart
    # turns "wrong bundle" into an explicit error here, instead of a
    # dependency resolution that blows up halfway through the install.
    case "$PKG_MGR" in
        zypper) OFFLINE=1 ;;
        *) die "The offline bundle contains openSUSE/SLES .rpm packages and this machine uses ${PKG_MGR}. Run the installer in ONLINE mode (delete or rename bundle/) or build the bundle for this family." ;;
    esac
elif [ -d "$BUNDLE_DIR" ] && [ -d "$BUNDLE_DIR/rpms" ]; then
    case "$PKG_MGR" in
        dnf|yum) OFFLINE=1 ;;
        *) die "The offline bundle contains .rpm packages (RHEL/Rocky/Alma family) and this machine uses ${PKG_MGR}. Run the installer in ONLINE mode (delete or rename bundle/) or build the bundle for this family." ;;
    esac
fi

echo ""
echo "┌──────────────────────────────────────────────────────────┐"
echo "│  SATOM ${VERSION} — Installer $( [ $OFFLINE -eq 1 ] && echo '(OFFLINE, local bundle)' || echo '(ONLINE)' )"
echo "└──────────────────────────────────────────────────────────┘"
echo ""

# ─────────────────────────────────────────────────────────────────────────────
# ─────────────────────────────────────────────────────────────────────────────
# STEP 0 — PREFLIGHT: do we have the permissions and environment to install? [PF0]
#
# Runs BEFORE asking anything and BEFORE modifying the system. Collects ALL
# problems and reports them together: whoever requests a change window needs
# the full list, not the first failure. It can be run dry:
#
#     sudo bash install-satom.sh --preflight
#
# Returns 0 if the machine is ready, 1 with the list of blockers if not.
# ─────────────────────────────────────────────────────────────────────────────
PF_FAIL=(); PF_WARN=()
pf_bad()  { PF_FAIL+=("$1"); echo "    ${c_red}✗${c_off} $1" | tee -a "$INSTALL_LOG"; }
pf_warn() { PF_WARN+=("$1"); warn "$1"; }
pf_have() { command -v "$1" >/dev/null 2>&1; }
# Does the OFFLINE bundle carry this package? Avoids promising "step 2 installs
# it" when there is no network and the package is not on the media.  [PFSUDO]
pf_bundle_has() {
    [ $OFFLINE -eq 1 ] || return 1
    ls "$BUNDLE_DIR"/debs/"$1"_*.deb  >/dev/null 2>&1 && return 0
    ls "$BUNDLE_DIR"/rpms/"$1"-[0-9]*.rpm >/dev/null 2>&1 && return 0
    ls "$BUNDLE_DIR"/rpms-suse/"$1"-[0-9]*.rpm >/dev/null 2>&1 && return 0
    return 1
}

pf_writable() {  # pf_writable <dir> → 0 if writable (walks up to the parent if it does not exist)
    local d="$1"
    while [ ! -d "$d" ] && [ "$d" != "/" ]; do d="$(dirname "$d")"; done
    local p="${d}/.satom-probe.$$"
    if ( : > "$p" ) 2>/dev/null; then rm -f "$p"; return 0; fi
    return 1
}

pf_free_mb() {   # pf_free_mb <path> → free MB on its mount point
    local d="$1"
    while [ ! -d "$d" ] && [ "$d" != "/" ]; do d="$(dirname "$d")"; done
    df -Pk "$d" 2>/dev/null | awk 'NR==2{printf "%d", $4/1024}'
}

pf_https_ok() {  # pf_https_ok <url> → 0 reachable · 1 not · 2 no tool [PFHTTPS]
    if pf_have curl; then curl -fsSk -m 8 -o /dev/null "$1" 2>/dev/null; return $?; fi
    # A minimal image may lack curl (installed in step 2), but python3 is
    # there: it works just as well to check HTTPS egress.
    local py="" c
    for c in python3.12 python3.11 python3; do pf_have "$c" && { py="$c"; break; }; done
    [ -n "$py" ] || return 2
    "$py" - "$1" <<'PFPY' 2>/dev/null
import sys, ssl, urllib.request
ctx = ssl.create_default_context(); ctx.check_hostname = False; ctx.verify_mode = ssl.CERT_NONE
try:
    urllib.request.urlopen(sys.argv[1], timeout=8, context=ctx)
except Exception:
    sys.exit(1)
PFPY
}

pf_git_probe() {  # pf_git_probe <repo-url> → prints the HTTP code, or nothing
    # Probes the REAL git endpoint, not the host root: a private repository
    # returns 401/403 here while the server root answers 200.
    local u="${1%.git}.git/info/refs?service=git-upload-pack"
    pf_have curl || return 2
    curl -sSk -m 8 -o /dev/null -w "%{http_code}" "$u" 2>/dev/null
}

pf_port_owner() {  # pf_port_owner <port> → name of the listening process, or nothing
    local line="" name=""                                              # [PFOWNER]
    if pf_have ss; then
        line="$(ss -Hlntp "sport = :$1" 2>/dev/null | head -1)"
    elif pf_have netstat; then
        line="$(netstat -lntp 2>/dev/null | awk -v p=":$1\$" '$4 ~ p {print; exit}')"
    fi
    [ -n "$line" ] || return 0
    # ss/netstat print users:(("nginx",pid=…)) — keep just the name.
    name="$(printf '%s' "$line" | grep -oE '"[^"]+"' | head -1 | tr -d '"')"
    [ -z "$name" ] && name="$(printf '%s' "$line" | awk '{print $NF}')"
    echo "$name"
}

preflight() {
    say "Step 0/7 — Preflight: permissions and environment (nothing is modified)"

    # ---- 1. PRIVILEGES ------------------------------------------------------
    # Being uid 0 is not enough: an unprivileged LXC, a read-only / or SELinux
    # can leave you "root" and unable to write where it matters.
    ok "Identity: root (uid 0)"
    local d
    for d in /opt /etc /etc/systemd/system /var/log /usr/local/sbin; do
        if pf_writable "$d"; then ok "Write access verified on ${d}"
        else pf_bad "No write access to ${d} — you are root but the filesystem prevents it (read-only mount, unprivileged LXC or SELinux)"; fi
    done

    # ---- 2. INIT ------------------------------------------------------------
    if [ -d /run/systemd/system ]; then ok "systemd is the init (PID 1)"
    else pf_bad "systemd is not running as PID 1 (the systemctl binary exists but there is no bus). Containers without systemd are not supported."; fi

    # ---- 3. PACKAGING -------------------------------------------------------
    ok "Package manager: ${PKG_MGR}$( [ $OFFLINE -eq 1 ] && echo ' (OFFLINE mode, local bundle)' )"

    # ---- 4. BINARIES THAT MUST COME WITH THE BASE IMAGE ---------------------
    # Step 2 does NOT install these: if they are missing, the image is too minimal.
    local miss=() b
    for b in useradd usermod passwd getent install runuser tar awk sed grep hostname df; do
        pf_have "$b" || miss+=("$b")
    done
    if [ ${#miss[@]} -eq 0 ]; then ok "Base utilities present (shadow, util-linux, coreutils)"
    else pf_bad "Missing base utilities: ${miss[*]} — install your distro's shadow/util-linux/coreutils packages"; fi
    pf_have ss || pf_have netstat || pf_warn "Neither 'ss' nor 'netstat': cannot check whether the ports are free"

    # ---- 4b. SUDO — the privilege model depends on it  [PFSUDO] -------------
    # Step 6 writes /etc/sudoers.d/satom and validates it with 'visudo -cf'. If
    # sudo is missing, that validation fails and the installer aborts AFTER it
    # has created the user and run chown -R on the tree. It is checked here so
    # it is an early, readable blocker, not a late failure halfway through.
    local sudo_miss=() sb
    for sb in sudo visudo; do pf_have "$sb" || sudo_miss+=("$sb"); done
    if [ ${#sudo_miss[@]} -eq 0 ]; then
        ok "sudo and visudo present (service allowlist: nginx -t, systemctl reload nginx)"
    elif [ $OFFLINE -eq 0 ]; then
        pf_warn "Missing ${sudo_miss[*]} — step 2 will install the 'sudo' package"
    elif pf_bundle_has sudo; then
        ok "Missing ${sudo_miss[*]}, but the offline bundle carries the 'sudo' package"
    else
        pf_bad "Missing ${sudo_miss[*]} and the OFFLINE bundle does not carry 'sudo'. Install it from your distro media and retry (step 6 needs it to write /etc/sudoers.d)."
    fi

    # ---- 5. PYTHON ----------------------------------------------------------
    local pv="" c
    for c in python3.12 python3.11 python3; do
        pf_have "$c" || continue
        if "$c" -c 'import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)' 2>/dev/null; then
            pv="$($c --version 2>&1)"; break
        fi
    done
    if [ -n "$pv" ]; then ok "Suitable Python: ${pv} (minimum 3.10)"
    else pf_warn "No Python >= 3.10 — the distro's will be installed in step 2"; fi

    # ---- 6. DISK AND MEMORY -------------------------------------------------
    local opt_mb var_mb ram_mb
    opt_mb=$(pf_free_mb /opt); var_mb=$(pf_free_mb /var)
    if [ "${opt_mb:-0}" -lt 4000 ]; then pf_bad "Only ${opt_mb} MB free on /opt — code + venv + reports need a lot more (4 GB minimum to operate, 15 GB recommended)"
    elif [ "${opt_mb:-0}" -lt 15000 ]; then pf_warn "/opt has ${opt_mb} MB free; 15 GB is the FLOOR, not a sizing. Work out the real size for your fleet with docs/sizing.md (~110 devices per node; disk is dominated by the configuration index, ~0.45 MB per server policy)"
    else ok "/opt: ${opt_mb} MB free"; fi
    if [ "${var_mb:-0}" -lt 2000 ]; then pf_warn "/var has only ${var_mb} MB free (Postgres and the logs live there)"
    else ok "/var: ${var_mb} MB free"; fi
    ram_mb=$(awk '/^MemTotal:/{printf "%d", $2/1024}' /proc/meminfo 2>/dev/null || echo 0)
    if [ "${ram_mb:-0}" -lt 1800 ]; then pf_warn "Total RAM ${ram_mb} MB — the supported minimum is 2 GB"
    else ok "RAM: ${ram_mb} MB"; fi

    # ---- 7. EXISTING INSTALLATION ------------------------------------------
    # Reinstalling on top of a live node rewrites .env and the service
    # configuration. It is an explicit blocker, not a warning.
    if systemctl is-active --quiet satom.service 2>/dev/null; then
        if [ "${SATOM_ALLOW_REINSTALL:-0}" = "1" ]; then
            pf_warn "satom.service is ACTIVE and SATOM_ALLOW_REINSTALL=1 — reinstalling on top at your own risk"
        else
            pf_bad "satom.service is already ACTIVE on this machine: reinstalling on top rewrites .env and the units. To upgrade, use the Software Update page, or export SATOM_ALLOW_REINSTALL=1 if you really want to reinstall."
        fi
    elif [ -d "${APP_DIR}/app" ]; then
        pf_warn "${APP_DIR} already contains code (service stopped) — it will be kept and only dependencies updated"
    else
        ok "No previous installation in ${APP_DIR}"
    fi

    # ---- 8. FIXED PRODUCT PORTS --------------------------------------------
    # The console port is asked in step 1 and checked there.
    # 80 (redirect + ACME challenge) and 8443 (inter-node probes) are fixed.
    local o
    for p in 80 8443; do
        o="$(pf_port_owner "$p")"
        [ -n "$o" ] && pf_warn "Port ${p} is already in use (${o}) — nginx needs it for $( [ "$p" = 80 ] && echo 'the redirect and the ACME challenge' || echo 'the inter-node probes' )"
    done

    # ---- 9. CLOCK -----------------------------------------------------------
    # A drifting clock breaks TLS, ACME validation and verify-ca replication.
    if pf_have timedatectl; then
        if [ "$(timedatectl show -p NTPSynchronized --value 2>/dev/null)" = "yes" ]; then
            ok "Clock synchronized by NTP ($(date -u '+%Y-%m-%dT%H:%M:%SZ'))"
        else
            pf_warn "The clock is NOT synchronized by NTP — TLS certificates and the ACME challenge will fail if it drifts"
        fi
    fi

    # ---- 10. NETWORK (ONLINE mode only) ------------------------------------
    if [ $OFFLINE -eq 0 ]; then
        local githost; githost="$(echo "$GIT_URL_DEFAULT" | awk -F/ '{print $3}')"
        if pf_have getent && ! getent hosts "$githost" >/dev/null 2>&1; then
            pf_warn "DNS does not resolve ${githost} (you can give another repo URL in step 3)"
        fi
        pf_https_ok "https://pypi.org/simple/"; case $? in            # [PFNET2]
            0) ok "PyPI egress verified (needed for the venv)" ;;
            1) pf_bad "No access to PyPI — the venv CANNOT be built. Use the OFFLINE bundle or open HTTPS egress." ;;
            *) pf_warn "Neither curl nor python3: cannot check Internet egress" ;;
        esac
        pf_https_ok "https://${githost}/"; case $? in
            0) ok "Code repository reachable (${githost})"
               # Reachable != clonable. A private repo answers 401 here.
               local _gitcode; _gitcode="$(pf_git_probe "$GIT_URL_DEFAULT")"
               case "$_gitcode" in
                   200|304) ok "Repository clonable without credentials" ;;
                   401|403) pf_warn "Repository ${GIT_URL_DEFAULT} is PRIVATE (HTTP ${_gitcode}). Step 3 will ask for a username/password; for an unattended install give the URL with a token: https://<user>:<token>@${githost}/..." ;;
                   404)     pf_warn "Repository ${GIT_URL_DEFAULT} returns 404 — wrong path or no read permission. You can correct the URL in step 3." ;;
                   "")      : ;;
                   *)       pf_warn "The repository answered HTTP ${_gitcode} — the clone in step 3 may fail" ;;
               esac ;;
            1) pf_warn "No access to https://${githost} — the clone will fail (you can give another URL in step 3)" ;;
        esac
    fi

    # ---- 11. SELINUX / APPARMOR (informational) ----------------------------
    if pf_have getenforce; then
        ok "SELinux: $(getenforce 2>/dev/null) $( [ "$(getenforce 2>/dev/null)" = "Enforcing" ] && echo '(the installer will apply the required booleans and ports)' )"
    fi

    # ---- SUMMARY ------------------------------------------------------------
    echo ""
    if [ ${#PF_FAIL[@]} -gt 0 ]; then
        echo "${c_red}${c_bold}PREFLIGHT: ${#PF_FAIL[@]} blocker(s).${c_off} Nothing has been modified." | tee -a "$INSTALL_LOG"
        local f; for f in "${PF_FAIL[@]}"; do echo "  ${c_red}✗${c_off} $f" | tee -a "$INSTALL_LOG"; done
        [ ${#PF_WARN[@]} -gt 0 ] && { echo "  — and ${#PF_WARN[@]} warning(s) —" ; for f in "${PF_WARN[@]}"; do echo "  ${c_ylw}!${c_off} $f"; done; }
        echo ""
        die "Fix the blockers and run again (or 'bash $0 --preflight' to re-check without installing)"
    fi
    if [ ${#PF_WARN[@]} -gt 0 ]; then
        echo "${c_ylw}${c_bold}PREFLIGHT OK with ${#PF_WARN[@]} warning(s):${c_off}" | tee -a "$INSTALL_LOG"
        local w; for w in "${PF_WARN[@]}"; do echo "  ${c_ylw}!${c_off} $w" | tee -a "$INSTALL_LOG"; done
    else
        echo "${c_grn}${c_bold}PREFLIGHT OK — the machine meets all requirements.${c_off}" | tee -a "$INSTALL_LOG"
    fi
    echo ""
}

# Cluster-specific preflight. Called as soon as the mode is known, which is as
# early as possible: the SSH binaries are only needed if there is a second node.
preflight_cluster() {
    say "Cluster preflight — SSH channel between nodes"
    local miss=() b
    for b in ssh ssh-keygen ssh-keyscan rsync; do pf_have "$b" || miss+=("$b"); done
    if [ ${#miss[@]} -eq 0 ]; then
        ok "SSH client and rsync present"
    elif [ $OFFLINE -eq 1 ]; then
        # OFFLINE: only fatal if the bundle does not carry them either. The
        # package for EACH missing binary is checked, not "any of them".  [PFSUDO]
        local nocover=() m sp covered
        for m in "${miss[@]}"; do
            covered=0
            if [ "$m" = "rsync" ]; then
                pf_bundle_has rsync && covered=1
            else
                for sp in "${SSH_PKGS[@]}"; do pf_bundle_has "$sp" && covered=1; done
            fi
            [ $covered -eq 1 ] || nocover+=("$m")
        done
        if [ ${#nocover[@]} -eq 0 ]; then
            ok "Missing ${miss[*]}, but the offline bundle carries their packages"
        else
            die "Cluster mode: ${nocover[*]} missing, you are OFFLINE and the bundle does not carry them (packages: ${SSH_PKGS[*]} rsync). Install them from the distro media and retry."
        fi
    else
        warn "Missing ${miss[*]} — step 2 will install them (${SSH_PKGS[*]} rsync)"
    fi
    # The PRIMARY must have sshd running: the standby syncs data/ by pulling.
    if systemctl list-unit-files 2>/dev/null | grep -qE '^(ssh|sshd)\.service'; then
        if systemctl is-active --quiet ssh 2>/dev/null || systemctl is-active --quiet sshd 2>/dev/null; then
            ok "SSH server installed and active"
        else
            warn "The SSH server is installed but not active. It must be running on the PRIMARY: the standby syncs data/ over SSH."
        fi
    else
        warn "No SSH server installed. It is mandatory on the PRIMARY (the standby pulls data/ over SSH); ${SSH_PKGS[*]} will be installed."
    fi
}

