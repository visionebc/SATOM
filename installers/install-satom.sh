# --- the interpreter has to WORK, not just exist --------------------------
# `--version` and `-m venv --help` import no C extension, so they cannot see
# an ABI mismatch between the Python binary and the system libraries. Real
# case (openSUSE Leap 15.6): the mirrors' python311 is built against libexpat
# 2.7.x, the base image ships 2.4.4 and `zypper install` does NOT upgrade an
# already-installed dependency -> `import pyexpat` fails with "undefined
# symbol" and the install dies in `ensurepip`, AFTER cloning the repo and
# creating the service account. It is checked here, remediated once, and if
# that fails the install dies naming the module and the command.
# [SATOM-ABI-OFFLINE] Forces an upgrade of the system libraries the
# interpreter was built against, USING THE BUNDLE as the only source.
# Only called once we know the interpreter is broken: libexpat/libssl are not
# touched on a machine whose Python works.
bundle_upgrade_abi_libs() {
    local rc=0
    if [ -d "$BUNDLE_DIR/rpms-suse" ]; then
        local _zr; _zr="$(mktemp -d)"
        mkdir -p "$_zr/repos.d" "$_zr/cache"
        cat > "$_zr/repos.d/satom-bundle.repo" <<ZREPO
[satom-bundle]
name=SATOM offline bundle
baseurl=dir://$BUNDLE_DIR/rpms-suse
enabled=1
autorefresh=0
gpgcheck=0
keeppackages=0
ZREPO
        # `install` and not `update`: update only looks at the repos registered
        # on the system. With --force-resolution zypper agrees to upgrade the
        # package even though the soname dependency was already satisfied.
        zypper --non-interactive --no-gpg-checks \
               --reposd-dir "$_zr/repos.d" --cache-dir "$_zr/cache" \
               install --no-recommends --auto-agree-with-licenses \
               --force-resolution \
               libexpat1 libopenssl3 libsqlite3-0 libz1 \
               >>"$INSTALL_LOG" 2>&1 || rc=1
        rm -rf "$_zr"
    elif [ -d "$BUNDLE_DIR/rpms" ]; then
        "$PKG_MGR" -y --disablerepo='*' \
            --repofrompath="satom-bundle,file://$BUNDLE_DIR/rpms" \
            --setopt=satom-bundle.gpgcheck=0 \
            --setopt=install_weak_deps=False \
            --allowerasing \
            upgrade expat openssl-libs sqlite-libs zlib \
            >>"$INSTALL_LOG" 2>&1 || rc=1
    elif [ -d "$BUNDLE_DIR/debs" ]; then
        # dpkg over the full set already upgrades whatever is newer; repeated
        # here in case the general pass skipped something.
        dpkg -i --skip-same-version "$BUNDLE_DIR"/debs/*.deb \
            >>"$INSTALL_LOG" 2>&1 || rc=1
    fi
    return $rc
}

PY_C_EXTENSIONS="pyexpat ssl sqlite3 ctypes zlib _hashlib"
py_runtime_broken() {
    for m in $PY_C_EXTENSIONS; do
        "$PYBIN" -c "import $m" >/dev/null 2>&1 || { echo "$m"; return 0; }
    done
    return 1
}
BROKEN_MOD="$(py_runtime_broken || true)"
if [ -n "$BROKEN_MOD" ]; then
    # `|| true` is NOT decorative: with `set -o pipefail` the pipeline returns
    # python's exit code, which fails ON PURPOSE (that is exactly what is being
    # measured), and `set -e` would kill the script on this assignment — the
    # diagnostic killing the very case it exists to diagnose. Found by
    # running it: `bash -n` cannot see it.
    BROKEN_ERR="$("$PYBIN" -c "import $BROKEN_MOD" 2>&1 | tail -1 || true)"
    warn "The interpreter $PYBIN cannot import '$BROKEN_MOD': $BROKEN_ERR"
    # The libraries that most often lag behind the interpreter.
    if [ "$OFFLINE" = "1" ]; then
        # [SATOM-ABI-OFFLINE] This used to be a bare `die`: "upgrade the
        # libraries from the same media". But the media IS the bundle, and the
        # bundle ALREADY CARRIES the right version — it is pulled in as a
        # python311 dependency when resolving against an empty root. What did
        # not happen was INSTALLING it: zypper sees the dependency satisfied by
        # soname (the template's 2.4.4 also provides libexpat.so.1) and does
        # not upgrade a package that is already there. Result: offline install
        # impossible on a base image with an old libexpat, with the remedy
        # sitting unused inside the tarball itself.
        # Found by really installing on the openSUSE 15.6 LXC template
        # (libexpat1 2.4.4, from 2024-09); the opensuse/leap docker container
        # the bundle was validated with shipped 2.7.1, so it passed cleanly:
        # THE VALIDATION ENVIRONMENT WAS NEWER THAN THE DEPLOYMENT ONE.
        say "Upgrading the system libraries used by the interpreter from the bundle…"
        bundle_upgrade_abi_libs || true
    else
        say "Trying to upgrade the system libraries used by the interpreter…"
        case "$PKG_MGR" in
            zypper) zypper --non-interactive update libexpat1 libopenssl3 libsqlite3-0 libz1 >>"$INSTALL_LOG" 2>&1 || true ;;
            dnf)    dnf -y upgrade expat openssl-libs sqlite-libs zlib          >>"$INSTALL_LOG" 2>&1 || true ;;
            yum)    yum -y update expat openssl-libs sqlite zlib               >>"$INSTALL_LOG" 2>&1 || true ;;
            apt)    apt-get install -y --only-upgrade libexpat1 libssl3 libsqlite3-0 zlib1g >>"$INSTALL_LOG" 2>&1 || true ;;
            pacman) pacman -S --noconfirm expat openssl sqlite zlib            >>"$INSTALL_LOG" 2>&1 || true ;;
        esac
    fi
    STILL="$(py_runtime_broken || true)"
    if [ -n "$STILL" ]; then
        if [ "$OFFLINE" = "1" ]; then
            die "The distro's Python is still broken after upgrading from the bundle: 'import $STILL' fails.
       The bundle does not carry a recent enough version of the system libraries
       for this base image. Upgrade the system from your own media and run the
       installer again. Nothing else has been modified. Details in $INSTALL_LOG"
        fi
        die "The distro's Python is still broken: 'import $STILL' fails. Upgrade the whole system (e.g. 'zypper update' / 'dnf upgrade') and run the installer again. Nothing else has been modified."
    fi
    ok "System libraries upgraded — the interpreter imports its C extensions"
else
    ok "Interpreter verified: it imports its C extensions ($PY_C_EXTENSIONS)"
fi

