    if [ -d /etc/nginx/sites-enabled ]; then
        ln -sf /etc/nginx/sites-available/satom.conf /etc/nginx/sites-enabled/satom.conf
        rm -f /etc/nginx/sites-enabled/default
    fi
    # [SATOM-NGINX-DEFAULT] The welcome site packaged by nginx.org and RHEL
    # lives in conf.d/default.conf and claims `listen 80 default_server`.
    # If it survives, it wins :80 by ALPHABETICAL order across files and the
    # HTTPS redirect stops firing while :443 stays perfect — the node looks
    # healthy. And with a duplicate default_server nginx rejects the WHOLE config.
    [ "$NGXCONF" = /etc/nginx/conf.d/default.conf ] || rm -f /etc/nginx/conf.d/default.conf
}

# Written WITH default_server. If another vhost already claimed it, nginx says
# so with "duplicate default server" and ONLY THEN is it rewritten without it.
# It self-corrects and does not depend on guessing someone else's config with
# a regex. An `nginx -t` failing for ANY other reason does NOT drop
# default_server: it falls through to the `nginx -t || die` further down,
