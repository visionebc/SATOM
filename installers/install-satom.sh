    esac
    printf '%s' "$CA_CRT" | grep -q -- "-----END CERTIFICATE-----" \
        || die "The join key's ca_crt is truncated (END line missing)"
    printf '%s' "$CA_KEY" | grep -q -- "PRIVATE KEY-----" \
        || die "The join key's ca_key is truncated"
    PRIMARY_NAME=$(jget primary_name)
    ok "Join key valid — primary at ${PRIMARY_IP}:${PRIMARY_PORT:-$WEB_PORT}"
